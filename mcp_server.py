# Fixed internal path FastMCP itself mounts at; the identity-resolving
# middleware below rewrites every /<secret>/... request to this path before
# FastMCP's own router ever sees it. FastMCP only supports one sse_path per
# instance, so per-user routing has to happen in front of it, not inside it.
_INTERNAL_SSE_PATH = "/_internal/sse"
_INTERNAL_MESSAGE_PATH = "/_internal/messages/"

_current_user: contextvars.ContextVar[str] = contextvars.ContextVar("_current_user", default="unknown")

# Maps a live SSE session_id -> username. The MCP SSE transport is a TWO-leg
# protocol: leg 1 is a GET to /sse that's gated by the per-user secret in the
# path; the server's reply to that GET tells the client "send your actual
# tool-call POSTs to /messages/?session_id=<X>" — a URL with NO secret in it,
# generated by mcp.sse_app() itself with no knowledge of the outer secret.
# So identity has to be captured once at handshake time (leg 1) and looked up
# by session_id on every subsequent tool-call POST (leg 2), rather than
# re-derived from the path on each request. Entries are removed when the SSE
# connection closes (see _IdentityMiddleware) — this is in-memory only and
# resets on redeploy, which is fine since sessions don't survive that anyway.
_session_users: dict[str, str] = {}


def current_user() -> str:
    """The username resolved from the secret in the URL path of the current
    request's SSE session — set by _IdentityMiddleware before any tool call
    runs. Never trust a 'user' argument passed by the model instead of this."""
    return _current_user.get()


